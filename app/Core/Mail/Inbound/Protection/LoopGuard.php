<?php

namespace App\Core\Mail\Inbound\Protection;

use App\Core\Mail\Inbound\InboundMailSettings;
use App\Core\Mail\Inbound\Parsing\ParsedInboundEmail;

/**
 * Spots mail no person wrote (#583): auto-replies, out-of-office notices,
 * bulk and mailing-list mail, bounces and our own messages. These are
 * ignored quietly: never posted and never answered, so no mail loop starts.
 */
final class LoopGuard
{
    private const AUTO_REPLY_SUBJECT = '/^\s*(auto(matic)?[\s-]*(reply|response)|autoreply|out of (the )?office|away from (the )?office|on leave|abwesenheitsnotiz|réponse automatique|delivery status notification|undeliverable|undelivered mail|mail delivery (failed|failure|subsystem)|returned mail)\b/i';

    public function __construct(private readonly InboundMailSettings $settings) {}

    public function reasonToIgnore(ParsedInboundEmail $email): ?string
    {
        $headers = $email->headers;
        $autoSubmitted = strtolower(trim((string) $headers->first('auto-submitted')));

        if ($autoSubmitted !== '' && $autoSubmitted !== 'no') {
            return 'auto_reply';
        }

        foreach (['x-autoreply', 'x-autorespond', 'x-autoresponder', 'x-autogenerated', 'x-auto-response'] as $name) {
            if ($headers->has($name)) {
                return 'auto_reply';
            }
        }

        if (preg_match('/^(bulk|list|junk|auto_reply)$/i', trim((string) $headers->first('precedence'))) === 1) {
            return 'bulk';
        }

        if ($headers->has('list-id') || $headers->has('list-unsubscribe')) {
            return 'mailing_list';
        }

        if ($this->isBounce($email)) {
            return 'bounce';
        }

        if (preg_match(self::AUTO_REPLY_SUBJECT, $email->subject) === 1) {
            return 'auto_reply';
        }

        if ($this->isOurOwnMail($email)) {
            return 'loop';
        }

        return null;
    }

    private function isBounce(ParsedInboundEmail $email): bool
    {
        $returnPath = trim((string) $email->headers->first('return-path'));
        $local = strtolower((string) strstr((string) $email->fromAddress, '@', true));

        return $returnPath === '<>'
            || in_array($local, ['mailer-daemon', 'postmaster', 'mail-daemon'], true)
            || str_contains(strtolower((string) $email->headers->first('content-type')), 'multipart/report');
    }

    private function isOurOwnMail(ParsedInboundEmail $email): bool
    {
        $from = (string) $email->fromAddress;
        $mailbox = $this->settings->mailbox();

        if ($from === '' || $mailbox === null) {
            return false;
        }

        $ours = [
            strtolower((string) config('mail.from.address')),
            strtolower((string) config('mail.reply_to.address')),
            $this->settings->address(),
        ];

        return in_array($from, $ours, true)
            || preg_match('/^'.preg_quote($mailbox['local'], '/').'\+[^@]*@'.preg_quote($mailbox['domain'], '/').'$/i', $from) === 1;
    }
}
